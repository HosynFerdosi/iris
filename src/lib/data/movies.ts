/**
 * Poster/backdrop/gallery images use Unsplash's stable photo CDN. Each
 * title's images are drawn from the same photo (via different Unsplash
 * crop params) so poster, backdrop, and gallery entries are visually
 * coherent rather than unrelated stock photography per field.
 */

function unsplash(id: string, w: number, h: number): string {
	return `https://images.unsplash.com/${id}?auto=format&fit=crop&w=${w}&h=${h}&q=80`
}

